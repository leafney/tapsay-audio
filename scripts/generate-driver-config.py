#!/usr/bin/env python3
"""Generate the C identity and audio defaults from the product metadata."""

import argparse
import json
import plistlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "config" / "product.json"
OUTPUT = ROOT / "Driver" / "TapSayAudio" / "TapSayAudioBuildConfig.h"


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--profile", choices=("reference-48k", "reference-16k"))
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args()
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    product = data["product"]
    driver = data["driver"]
    if args.profile:
        if args.output_dir is None:
            parser.error("--output-dir is required with --profile")
        profile_data = json.loads((ROOT / "config" / "driver-profiles.json").read_text(encoding="utf-8"))
        rates_data = profile_data["sample_rates_hz"]
        default_rate = profile_data["profiles"][args.profile]["default_sample_rate_hz"]
        output_dir = args.output_dir.resolve()
        output_dir.mkdir(parents=True, exist_ok=True)
        header_path = output_dir / "TapSayAudioBuildConfig.h"
        plist_path = output_dir / "TapSayAudio.plist"
        plist_template_path = ROOT / "Driver" / "TapSayAudio" / "TapSayAudio.plist"
        driver2 = profile_data["device2"]
        device = profile_data["device"]
    else:
        if args.output_dir is not None:
            parser.error("--output-dir can only be used with --profile")
        rates_data = driver["sample_rates_hz"]
        default_rate = driver["default_sample_rate_hz"]
        header_path = OUTPUT
        plist_path = ROOT / "Driver" / "TapSayAudio" / "TapSayAudio.plist"
        plist_template_path = plist_path
        driver2 = {"uid": "", "name": "", "hidden": True, "has_input": True, "has_output": True}
        device = {"hidden": False, "has_input": True, "has_output": True}
    rates = ", ".join(str(rate) for rate in rates_data)
    definitions = [
        "/* Generated by generate-driver-config.py. Do not edit by hand. */",
        f"#define TAPSAY_PROFILE_NAME {c_string(args.profile or 'legacy')}",
        f"#define TAPSAY_ENABLE_REFERENCE_PROFILE {1 if args.profile else 0}",
        "#define TAPSAY_BOX_TRANSPORT_TYPE kAudioDeviceTransportTypeVirtual" if args.profile else
        "#define TAPSAY_BOX_TRANSPORT_TYPE kAudioDeviceTransportTypeUSB",
        f"#define TAPSAY_PRODUCT_NAME {c_string(product['name'])}",
        f"#define TAPSAY_PRODUCT_VERSION {c_string(product['version'])}",
        f"#define TAPSAY_DEFAULT_SAMPLE_RATE {default_rate}.0",
        f"#define kPlugIn_BundleID {c_string(driver['bundle_identifier'])}",
        f"#define kBox_UID {c_string(driver['box_uid'])}",
        f"#define kDevice_UID {c_string(driver['device_uid'])}",
        f"#define kDevice2_UID {c_string(driver2['uid'])}",
        f"#define kDevice_ModelUID {c_string(driver['model_uid'])}",
        f"#define kDevice_Name {c_string(driver['device_name'])}",
        f"#define kDevice2_Name {c_string(driver2['name'])}",
        f"#define kDevice_IsHidden {'true' if device['hidden'] else 'false'}",
        f"#define kDevice2_IsHidden {'true' if driver2['hidden'] else 'false'}",
        f"#define kDevice_HasInput {'true' if device['has_input'] else 'false'}",
        f"#define kDevice_HasOutput {'true' if device['has_output'] else 'false'}",
        f"#define kDevice2_HasInput {'true' if driver2['has_input'] else 'false'}",
        f"#define kDevice2_HasOutput {'true' if driver2['has_output'] else 'false'}",
        f"#define kManufacturer_Name {c_string(driver['manufacturer'])}",
        f"#define kNumber_Of_Channels {driver['channels']}",
        f"#define kSampleRates {rates}",
    ]
    header_content = "\n".join(definitions) + "\n"
    temporary_header = header_path.with_suffix(header_path.suffix + ".tmp")
    temporary_header.write_text(header_content, encoding="utf-8")
    info = plistlib.loads(plist_template_path.read_bytes())
    info["CFPlugInFactories"] = {driver["plugin_factory_uuid"]: "TapSayAudio_Create"}
    info["CFPlugInTypes"] = {driver["audio_server_plugin_type_uuid"]: [driver["plugin_factory_uuid"]]}
    if args.profile:
        info["TapSayAudioProfile"] = args.profile
        info["TapSayAudioDefaultSampleRate"] = default_rate
        info["TapSayAudioSupportedSampleRates"] = rates_data
    temporary_plist = plist_path.with_suffix(plist_path.suffix + ".tmp")
    temporary_plist.write_bytes(plistlib.dumps(info, sort_keys=False))
    temporary_header.replace(header_path)
    temporary_plist.replace(plist_path)
    if args.profile:
        manifest = {
            "profile": args.profile,
            "default_sample_rate_hz": default_rate,
            "sample_rates_hz": rates_data,
            "device": profile_data["device"],
            "device2": profile_data["device2"],
            "box_transport": profile_data["box_transport"],
            "latency_frame_size": profile_data["latency_frame_size"],
            "device_ring_buffer_size": profile_data["device_ring_buffer_size"],
            "ring_buffer_frame_size": profile_data["ring_buffer_frame_size"],
            "product_identity": driver,
        }
        manifest_path = output_dir / "profile-manifest.json"
        temporary_manifest = manifest_path.with_suffix(".json.tmp")
        temporary_manifest.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        temporary_manifest.replace(manifest_path)
    print(f"Generated {header_path} and plugin registration")


if __name__ == "__main__":
    main()
